export const adminCatalogTranslations: Record<Locale, AdminCatalogTranslations> = {
  en: english,
  vi: vietnamese,
};

export function getAdminCatalogTranslations(locale: Locale): AdminCatalogTranslations {
  return adminCatalogTranslations[locale];
}

export function getAdminCatalogErrorMessage(
  error: unknown,
  messages: Readonly<Record<string, string>>,
  fallback: string,
): string {
  if (error instanceof ApiClientError) {
    return messages[error.code] || fallback;
  }

  return fallback;
}

export function getAdminCatalogIntlLocale(locale: Locale): "en-US" | "vi-VN" {
  return locale === "vi" ? "vi-VN" : "en-US";
}

export function formatAdminCatalogNumber(value: number, locale: Locale): string {
  return new Intl.NumberFormat(getAdminCatalogIntlLocale(locale)).format(value);
}

export function formatAdminCatalogMoney(value: number, locale: Locale): string {
  return new Intl.NumberFormat(getAdminCatalogIntlLocale(locale), {
    currency: "VND",
    currencyDisplay: "code",
    maximumFractionDigits: 0,
    style: "currency",
  }).format(value);
}

export function formatAdminCatalogPercent(value: number, locale: Locale): string {
  return new Intl.NumberFormat(getAdminCatalogIntlLocale(locale), {
    maximumFractionDigits: 0,
    style: "percent",
  }).format(value / 100);
}
